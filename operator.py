# Arithmatic operator
a = 1
b = 4
c = a + b
print(c)

#Assignment Operators
a= 4-2 # Assign 4-2 ie 2 to a
print(a)
b=6
b+=3 # Increments the value of b by 3 and then assigns it to b
print(b)

# Comparision operators
"""
  this operators only returns the boolean value
  ie. True or False
"""
d = 5>4
print(d)

d = 5>=4
print(d)

d = 5!=5
print(d)

d = 5==4
print(d)

# Logical Operators
e = 1 or 0    # or operator
print(e)

e = True or False
print(e)

e = 1 and 0   # and operator
print(e)

e = not(1)
print("not:",e)    # returns True if False and vise versa

